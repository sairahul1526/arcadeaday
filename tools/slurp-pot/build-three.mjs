#!/usr/bin/env node
// Slurp Pot: bundle tools/slurp-pot/three-entry.js → games/slurp-pot/vendor/three.bundle.js (GDD §11.5, D11).
// ESM, minified, tree-shaken, es2020. Fails (exit 1) above 600 KiB raw; warns above 160 KiB gzip.
// Usage: node tools/slurp-pot/build-three.mjs
import { build } from 'esbuild';
import { readFileSync, mkdirSync, statSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const entry = resolve(here, 'three-entry.js');
const out = resolve(root, 'games/slurp-pot/vendor/three.bundle.js');
const RAW_MAX = 600 * 1024, GZ_MAX = 160 * 1024;

mkdirSync(dirname(out), { recursive: true });
const ver = JSON.parse(readFileSync(resolve(root, 'node_modules/three/package.json'), 'utf8')).version;
await build({
  entryPoints: [entry],
  outfile: out,
  bundle: true,
  format: 'esm',
  minify: true,
  treeShaking: true,
  target: 'es2020',
  platform: 'browser',
  legalComments: 'none',
  banner: { js: `/* three.js r${ver.split('.')[1]} (MIT) subset for Slurp Pot; generated by tools/slurp-pot/build-three.mjs, do not edit */` },
  logLevel: 'warning',
});

const buf = readFileSync(out);
const raw = statSync(out).size, gz = gzipSync(buf, { level: 9 }).length;
const kib = n => (n / 1024).toFixed(1) + ' KiB';
console.log('three.bundle.js  three@' + ver);
console.log('  raw  ' + kib(raw).padStart(10) + '   budget ' + kib(RAW_MAX));
console.log('  gzip ' + kib(gz).padStart(10) + '   budget ' + kib(GZ_MAX));
if (raw > RAW_MAX) { console.error('FAIL: bundle above 600 KiB raw'); process.exit(1); }
if (gz > GZ_MAX) console.warn('WARN: bundle above 160 KiB gzip');
console.log('OK → ' + out.slice(root.length + 1));
